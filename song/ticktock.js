    function lzwEncode(ind,mcs,out){
      /* the writer's half of the 1989 format: variable-width codes, a
         table reset at 4096, packed lsb-first into 255-byte sub-blocks */
      const CLR=1<<mcs, END=CLR+1;
      let size=mcs+1, next=END+1;
      let table=new Map();
      let cur=0, bits=0; const blk=[];
      const emit=c=>{ cur|=c<<bits; bits+=size;
        while(bits>=8){ blk.push(cur&255); cur>>>=8; bits-=8;
          if(blk.length===255){ out.push(255); for(const b of blk) out.push(b); blk.length=0; } } };
      emit(CLR);
      let prefix=ind[0];
      for(let i=1;i<ind.length;i++){
        const k=ind[i], key=(prefix<<8)|k, e=table.get(key);
        if(e!==undefined){ prefix=e; continue; }
        emit(prefix);
        if(next<4096){ table.set(key,next++); if(next>(1<<size)&&size<12) size++; }
        else{ emit(CLR); table=new Map(); size=mcs+1; next=END+1; }
        prefix=k;
      }
      emit(prefix); emit(END);
      if(bits>0){ blk.push(cur&255); if(blk.length===255){ out.push(255); for(const b of blk) out.push(b); blk.length=0; } }
      if(blk.length){ out.push(blk.length); for(const b of blk) out.push(b); }
      out.push(0);
    }
