      const b=actx.createBuffer(1,len,sr), ch=b.getChannelData(0);
      const R=mulberry32((SEED^0x53544152^Math.imul(song.k,2654435761))>>>0);
      /* add — a decaying sine at P×frac, from sample s0, wrapping */
      const add=(frac,s0,amp,dec,atk)=>{
        const f=P*frac, n=Math.min(len,Math.round(sr*dec*6));
        for(let i=0;i<n;i++){ const t=i/sr;
          const v=Math.sin(2*Math.PI*f*t)*Math.exp(-t/dec)*(1-Math.exp(-t/(atk||0.003)))*amp;
          ch[(s0+i)%len]+=v; }
      };
      const beat=k=>Math.round(k*per*sr);
      /* the kick, on every beat: the heart's own trick — a ×1/4 body a
         telephone speaker cannot say, struck with the ×1 knock it can */
      const kickAmp=0.55+R()*0.2;
      for(let k=0;k<16;k++){ add(0.25,beat(k),kickAmp,0.14,0.004); add(1,beat(k),0.26,0.028,0.0012); }
      /* the bass, dealt from the lub/dub table: on 1 and 3, and sometimes
         the `and` of 4 */
