    function lzw(mcs,parts,npix){
      const out=new Uint8Array(npix); let op=0;
      const CLR=1<<mcs, END=CLR+1;
      let size=mcs+1, max=1<<size, next=END+1;
      const pref=new Int32Array(4096), suff=new Uint8Array(4096);
      const st=new Uint8Array(4097); let sp=0;
      let cur=0, bits=0, prev=-1, first=0, pi=0, bi=0;
      function code(){
        while(bits<size){
          if(pi>=parts.length) return END;
          cur|=parts[pi][bi++]<<bits; bits+=8;
          if(bi>=parts[pi].length){ pi++; bi=0; }
        }
        const c=cur&(max-1); cur>>=size; bits-=size; return c;
      }
      while(op<npix){
        let c=code();
        if(c===END) break;
        if(c===CLR){ size=mcs+1; max=1<<size; next=END+1; prev=-1; continue; }
        const inCode=c;
        if(c>=next){ st[sp++]=first; c=prev; }
        while(c>END){ st[sp++]=suff[c]; c=pref[c]; }
        first=c&0xFF; st[sp++]=first;
        while(sp&&op<npix) out[op++]=st[--sp];
        sp=0;
        if(prev>=0&&next<4096){
          pref[next]=prev; suff[next]=first; next++;
          if(next>=max&&size<12){ size++; max=1<<size; }
        }
        prev=inCode;
      }
      return out;
    }
